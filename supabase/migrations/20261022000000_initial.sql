-- Fonte oficial de dados da aplicação em produção.
create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  email text primary key check (email = lower(trim(email))),
  created_at bigint not null default extract(epoch from now())::bigint
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.admin_users where email = lower(coalesce(auth.jwt()->>'email', ''))) $$;

create table if not exists public.submission_attempts (
  id bigint generated by default as identity primary key,
  fingerprint_hash text not null,
  kind text not null check (kind in ('registration','shirt')),
  created_at bigint not null
);
create index if not exists submission_attempts_fingerprint_created_idx on public.submission_attempts(fingerprint_hash, created_at);

create table if not exists public.submission_receipts (
  id bigint generated by default as identity primary key,
  idempotency_key text not null unique,
  protocol text not null,
  kind text not null check (kind in ('registration','shirt')),
  created_at bigint not null
);

create table if not exists public.camp_registrations (
  id bigint generated by default as identity primary key,
  protocol text not null unique,
  idempotency_key text not null unique,
  full_name text not null, age integer not null check (age between 0 and 120), guardian_name text,
  phone text not null, church text not null, location text not null, allergies text, medication text,
  dietary_restrictions text, attended_before text not null, shirt_size text not null,
  payment_method text not null, payment_status text not null default 'pending',
  registration_status text not null default 'pending', notes text, receipt_key text,
  receipt_name text, receipt_type text, consent_at bigint not null, privacy_version text not null,
  created_at bigint not null, updated_at bigint not null
);
create index if not exists camp_registrations_status_created_idx on public.camp_registrations(registration_status, created_at desc);

create table if not exists public.shirt_orders (
  id bigint generated by default as identity primary key,
  protocol text not null unique, idempotency_key text not null unique, full_name text not null,
  phone text not null, edition text not null, size text not null, quantity integer not null check (quantity between 1 and 20),
  payment_method text not null, payment_status text not null default 'pending', order_status text not null default 'pending',
  consent_at bigint not null, privacy_version text not null, created_at bigint not null, updated_at bigint not null
);
create index if not exists shirt_orders_status_created_idx on public.shirt_orders(order_status, created_at desc);

create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key, actor_email text not null, action text not null,
  entity_type text not null, entity_id bigint, details jsonb, created_at bigint not null
);
create index if not exists admin_audit_created_idx on public.admin_audit_logs(created_at desc);

-- Atomic rate-limit decision; called only by the server-side service-role client.
create or replace function public.consume_submission_attempt(p_fingerprint_hash text, p_kind text, p_now bigint, p_window_start bigint)
returns boolean language plpgsql security definer set search_path = public
as $$
declare allowed boolean;
begin
  delete from public.submission_attempts where created_at < p_now - 86400;
  select count(*) < 5 into allowed from public.submission_attempts where fingerprint_hash = p_fingerprint_hash and created_at >= p_window_start;
  if allowed then insert into public.submission_attempts(fingerprint_hash, kind, created_at) values (p_fingerprint_hash, p_kind, p_now); end if;
  return allowed;
end $$;

-- Only the trusted server client may consume rate-limit slots.
revoke all on function public.consume_submission_attempt(text, text, bigint, bigint) from public, anon, authenticated;
grant execute on function public.consume_submission_attempt(text, text, bigint, bigint) to service_role;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('receipts', 'receipts', false, 5242880, array['application/pdf','image/jpeg','image/png','image/webp']::text[])
on conflict (id) do update set public = false, file_size_limit = 5242880;

alter table public.admin_users enable row level security;
alter table public.camp_registrations enable row level security;
alter table public.shirt_orders enable row level security;
alter table public.admin_audit_logs enable row level security;
alter table public.submission_attempts enable row level security;
alter table public.submission_receipts enable row level security;

-- The server-side secret key uses the service_role database role. Keep these
-- grants explicit because newer Supabase projects do not grant Data API table
-- privileges to service_role automatically for SQL-created tables.
grant select, insert, update, delete on table public.admin_users, public.camp_registrations, public.shirt_orders, public.admin_audit_logs, public.submission_attempts, public.submission_receipts to service_role;
grant usage, select, update on all sequences in schema public to service_role;
grant execute on function public.consume_submission_attempt(text, text, bigint, bigint) to service_role;

create policy "admins read registrations" on public.camp_registrations for select to authenticated using (public.is_admin());
create policy "admins update registrations" on public.camp_registrations for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admins read shirt orders" on public.shirt_orders for select to authenticated using (public.is_admin());
create policy "admins update shirt orders" on public.shirt_orders for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admins read audit" on public.admin_audit_logs for select to authenticated using (public.is_admin());
create policy "admins write audit" on public.admin_audit_logs for insert to authenticated with check (public.is_admin());
create policy "admins download receipts" on storage.objects for select to authenticated using (bucket_id = 'receipts' and public.is_admin());

